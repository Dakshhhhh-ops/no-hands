import type { Project } from '../types/schema.ts';
import { generateMultiServiceOpenApi } from './openapiSynth.ts';

const words = (text: string) => String(text).split(/[^A-Za-z0-9]+/).filter(Boolean);
const pascal = (text: string) => words(text).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('') || 'Project';
const camel = (text: string) => {
  const p = pascal(text);
  return p.charAt(0).toLowerCase() + p.slice(1);
};

/**
 * Generates a TypeScript client from the multi-service OpenAPI document: one
 * method per API operation in the model. Payload types stay open because the
 * model does not define request or response fields.
 */
export function generateTypeScriptSdk(project: Project): string {
  const spec = generateMultiServiceOpenApi(project);
  // The synthesized document always lists exactly one (placeholder) server.
  const serverUrl = spec.servers[0]?.url ?? '';
  const className = `${pascal(project.name)}Client`;
  const methods: string[] = [];
  const used = new Set<string>();

  for (const [path, item] of Object.entries(spec.paths)) {
    for (const [method, operation] of Object.entries(item as Record<string, { operationId?: string; summary?: string; tags?: string[] }>)) {
      let name = camel(operation.operationId || `${method} ${path}`);
      while (used.has(name)) name = `${name}2`;
      used.add(name);
      const hasBody = method !== 'get' && method !== 'delete';
      const owner = operation.tags?.[0] ? `${operation.tags[0]}: ` : '';
      methods.push(`  /**
   * ${owner}${operation.summary || `${method.toUpperCase()} ${path}`}
   * ${method.toUpperCase()} ${path}
   */
  async ${name}(${hasBody ? 'body: Record<string, unknown> = {}' : ''}): Promise<unknown> {
    return this.request<unknown>('${path}', {
      method: '${method.toUpperCase()}',${hasBody ? '\n      body: JSON.stringify(body),' : ''}
    });
  }`);
    }
  }

  return `/**
 * ==============================================================================
 * Generated TypeScript Client SDK
 * System: ${project.name} (v${project.version})
 * Generated by VoiceArchitect from the model's ${methods.length} API operation${methods.length === 1 ? '' : 's'}.
 * Request and response fields are typed as unknown because the model does not
 * define them yet.
 * ==============================================================================
 */

export interface SdkConfig {
  baseUrl?: string;
  authToken?: string;
  timeoutMs?: number;
}

export interface ApiError {
  error: string;
  statusCode: number;
}

export class ${className} {
  private baseUrl: string;
  private authToken?: string;
  private timeoutMs: number;

  constructor(config: SdkConfig = {}) {
    this.baseUrl = config.baseUrl || '${serverUrl}';
    this.authToken = config.authToken;
    this.timeoutMs = config.timeoutMs || 8000;
  }

  setAuthToken(token: string): void {
    this.authToken = token;
  }

  private async request<T>(endpoint: string, options: RequestInit = {}): Promise<T> {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), this.timeoutMs);
    const headers: Record<string, string> = {
      'Content-Type': 'application/json',
      Accept: 'application/json',
      ...(this.authToken ? { Authorization: \`Bearer \${this.authToken}\` } : {}),
    };
    try {
      const response = await fetch(\`\${this.baseUrl}\${endpoint}\`, { ...options, headers, signal: controller.signal });
      if (!response.ok) {
        throw { error: 'HTTP_ERROR', statusCode: response.status } as ApiError;
      }
      return (await response.json()) as T;
    } finally {
      clearTimeout(timer);
    }
  }

${methods.join('\n\n')}
}
`;
}
